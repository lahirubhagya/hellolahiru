                                                        Overview
                                                    </li>
                                                </ul>
                                            </div>

                                            <p class="custom_paragraph_option_1">
                                                Cargills Ceylon PLC, one of Sri Lanka's leading retail and food service
                                                conglomerates, required a unified digital solution to manage and
                                                monitor the daily field operations of its excursion officers across
                                                its extensive network of retail outlets — including KFC franchise branches.
                                            </p>
                                            <p class="custom_paragraph_option_1">
                                                The result is the Cargills Field Force Application: a dual-platform (web and mobile)
                                                system designed to streamline itinerary planning, real-time visit tracking, outlet
                                                compliance, checklist-based task management, and executive-level reporting —
                                                all within a single, cohesive interface.
                                            </p>

                                            <div class="dec-list  custom_paragraph_option_1">
                                                <ul class="ul_paragraph">
                                                    <li>
                                                        Who Uses the System ?
                                                    </li>
                                                </ul>
                                            </div>

                                            <p class="custom_paragraph_option_1">
                                                The application serves three distinct user groups, each with tailored
                                                access and functionality designed to match their operational responsibilities.
                                            </p>

