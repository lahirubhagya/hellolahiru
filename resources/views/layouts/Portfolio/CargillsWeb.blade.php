                                            <div class="dec-list  custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <ul class="ul_paragraph">
                                                    <li>
                                                        Key Feature Modules
                                                    </li>
                                                </ul>
                                            </div>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                Five interconnected modules work together to deliver end-to-end visibility and control over field operations.
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <b>1. Itinerary Management :</b>
                                                Area Managers can create, assign, and update itineraries
                                                for field officers on a daily, weekly, or monthly basis. Each itinerary captures destination,
                                                purpose, date, and time — fully editable and versioned.
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <b>2. Visit Tracking & Check-In/Out:</b>

                                                Field Officers use the mobile app to check in and out
                                                of each outlet location. The system automatically records timestamps and GPS coordinates,
                                                creating an auditable trail of every site visit.
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <b>3. Deviation Alerts & Geolocation:</b>

                                                When a field officer deviates from a planned route or itinerary,
                                                the system triggers a real-time alert. Officers can update their status and add comments to explain
                                                deviations directly within the app.
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <b>4. Checklists & Image Verification:</b>

                                                Area Managers build custom checklists for each visit.
                                                Field Officers complete these on-site and can upload photographic evidence within each checklist item.
                                                Images can be saved, reviewed, and deleted as needed.
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <b>5. Dashboard & Reporting: </b>

                                                Area Managers view a live dashboard summarising visit completion rates,
                                                task statuses, and compliance metrics. Operation Managers and COOs can generate daily, weekly,
                                                and monthly compliance reports on demand.
                                            </p>

                                            <div class="dec-list custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <ul class="ul_paragraph">
                                                    <li>
                                                        Visual Language & Brand Decisions
                                                    </li>
                                                </ul>
                                            </div>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                Every design decision was grounded in Cargills' brand identity and core usability principles —
                                                ensuring field officers can access critical information quickly, even in fast-paced environments.
                                            </p>

                                            <p class="custom_paragraph_option_1">
                                                <b>Color Palette</b>
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <b>1. Primary Color</b> - Red (#E31837): Directly sourced from Cargills' official brand identity.
                                                Used for interactive elements, CTAs, headers, and active states to ensure strong brand recall.<br>

                                                <b>2. Secondary Color</b> — Gray Scale: Gray and its variations provide neutral balance,
                                                structure, and hierarchy without competing with the brand red.<br>

                                                <b>3. Default Theme</b> - Default light theme maximises readability, ensures information clarity,
                                                and creates a clean, professional interface for data-heavy screens.<br>
                                            </p>

                                            <p class="custom_paragraph_option_1">
                                                <b>Typography</b>
                                            </p>

                                            <p class="custom_paragraph_option_1">
                                                Font Family: Poppins - chosen for its clean, professional appearance and excellent readability across all devices.
                                            </p>




                                            <div class="dec-list  custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                <ul class="ul_paragraph">
                                                    <li>
                                                        Design Decisions & Rationale
                                                    </li>
                                                </ul>
                                            </div>

                                            <p class="custom_paragraph_option_1">
                                                Every interface decision was guided by real-world operational constraints and user behaviour in field environments.
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                1. <b>Clarity Over Complexity :</b> Field officers operate in busy, often fast-paced environments.
                                                The UI prioritises large tap targets, minimal input steps, and bold visual
                                                hierarchy — so users find the right action instantly.<br>
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                2. <b>Mobile-First Thinking :</b> The mobile app was designed ground-up for one-handed use with
                                                thumb-friendly navigation. Key actions (check-in, checklist, image upload) are accessible
                                                within two taps from the home screen.<br>
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                3. <b>Consistent Brand Identity :</b> Using Cargills' brand red as the primary interactive colour
                                                across both platforms creates a seamless, recognisable experience — reinforcing
                                                trust and reducing the learning curve.<br>
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                4. <b>Progressive Disclosure :</b> Complex workflows (e.g. deviation reporting) are broken into contextual
                                                steps, only surfacing advanced options when needed — reducing cognitive load for everyday tasks.<br>
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                5. <b>Data Legibility :</b> Dashboard screens use card-based layouts, clear numerical metrics, and status
                                                colour-coding (red/amber/green) to allow at-a-glance understanding of field performance.<br>
                                            </p>

                                            <p class="custom_paragraph_option_1" style="margin-top: 0.3% !important;">
                                                6. <b>Accessible Typography :</b> Poppins was selected for its excellent screen rendering at all sizes,
                                                geometric clarity, and multilingual support — ensuring readability across devices and contexts.<br>
                                            </p>

                                            <div class="dec-list  custom_paragraph_option_1" style="margin-top: 0.3% !important;">
